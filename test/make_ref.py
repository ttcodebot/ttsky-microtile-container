"""Write the reference model for the gate level test: the container RTL (src/project.v) and the
RTL of every micro tile, taken as they are from the micro tile repositories, with every module
renamed to ref_<name>, so that the reference can be simulated next to the gate level netlists
(which use the original names).

Usage: make_ref.py <output file> <verilog file> [<verilog file> ...]
"""

import pathlib
import re
import sys

out, *sources = sys.argv[1:]
texts = [pathlib.Path(s).read_text() for s in sources]
modules = sorted({m for t in texts for m in re.findall(r"^\s*module\s+(\w+)", t, re.M)}, key=len, reverse=True)
pattern = re.compile(r"\b(" + "|".join(map(re.escape, modules)) + r")\b")

with open(out, "w") as f:
    f.write("// Generated by make_ref.py, do not edit: reference RTL with modules renamed to ref_*\n")
    for source, text in zip(sources, texts):
        f.write(f"\n// ---- {source}\n")
        f.write(pattern.sub(lambda m: "ref_" + m.group(1), text))
        f.write("\n`default_nettype wire\n")
print(f"make_ref.py: {len(modules)} modules renamed ({', '.join(sorted(modules))}) -> {out}", file=sys.stderr)
